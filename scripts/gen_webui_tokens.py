"""Generate webui/tokens.css from the design system's tokens.json.

Usage: python3 scripts/gen_webui_tokens.py
       python3 scripts/gen_webui_tokens.py --check   (exit 1 if tokens.css is stale)
"""

import argparse
import json
import os
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
SOURCE = os.path.join(ROOT, 'docs', 'design-system', 'tokens.json')
TARGET = os.path.join(ROOT, 'webui', 'tokens.css')
FONT_URLS = {'Azeret Mono': 'lib/azeret-mono.woff2'}
SKIP_FAMILIES = ('name', 'version', 'color', 'type', 'shadow', 'meta')


def theme_value(value, theme, first):
	if isinstance(value, str):
		return value
	return value.get(theme, value[first])


def css_color(value):
	# an alias "{other-token}" becomes a reference to that token
	if value.startswith('{') and value.endswith('}'):
		return 'var(--%s)' % value[1:-1]
	return value


def generate(tokens):
	themes = [theme['id'] for theme in tokens['color']['themes']]
	first = themes[0]
	out = [
		'/* NZBGet Design System tokens - generated by scripts/gen_webui_tokens.py',
		'   from docs/design-system/tokens.json. Do not edit by hand. Dark is the first theme. */',
		'',
	]
	for font in tokens['type'].get('fonts', []):
		url = FONT_URLS[font['family']]
		out += [
			'@font-face {',
			'\tfont-family: "%s";' % font['family'],
			'\tsrc: url(%s) format("woff2");' % url,
			'\tfont-weight: %s;' % font['weight'],
			'\tfont-style: %s;' % font.get('style', 'normal'),
			'\tfont-display: swap;',
			'}',
			'',
		]
	for index, theme in enumerate(themes):
		out.append((':root,\n[data-theme="%s"]' if index == 0 else '[data-theme="%s"]') % theme + ' {')
		for token in tokens['color']['tokens']:
			value = token['value']
			if index > 0 and isinstance(value, dict) and theme not in value:
				continue
			out.append('\t--%s: %s;' % (token['name'], css_color(theme_value(value, theme, first))))
		for token in tokens.get('shadow', {}).get('tokens', []):
			value = token['value']
			if index > 0 and isinstance(value, dict) and theme not in value:
				continue
			out.append('\t--%s: %s;' % (token['name'], theme_value(value, theme, first)))
		out += ['}', '']
	out.append(':root {')
	for family, group in tokens.items():
		if family in SKIP_FAMILIES:
			continue
		for token in group['tokens']:
			out.append('\t--%s: %s;' % (token['name'], token['value']))
	for key, stack in tokens['type']['families'].items():
		out.append('\t--font-%s: %s;' % (key, stack))
	out.append('}')
	return '\n'.join(out) + '\n'


def main():
	parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
	parser.add_argument('--check', action='store_true', help='fail if webui/tokens.css is not up to date')
	args = parser.parse_args()
	with open(SOURCE, encoding='utf-8') as source:
		css = generate(json.load(source))
	if args.check:
		with open(TARGET, encoding='utf-8') as target:
			if target.read() != css:
				print('webui/tokens.css is stale: run scripts/gen_webui_tokens.py')
				return 1
		print('webui/tokens.css is up to date')
		return 0
	with open(TARGET, 'w', encoding='utf-8') as target:
		target.write(css)
	print('wrote webui/tokens.css')
	return 0


if __name__ == '__main__':
	sys.exit(main())
