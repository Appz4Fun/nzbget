//! Ordered folding of little-endian CRC bytes in PAR2 verification entries.
//! Hashes, packet ownership, padding and file reads remain in C++.

#[cfg(test)]
use crate::crc;

fn required_len(stride: usize, count: usize) -> Option<usize> {
    if count == 0 {
        return Some(0);
    }
    if stride < 4 {
        return None;
    }
    (count - 1).checked_mul(stride)?.checked_add(4)
}

/// Fold CRCs starting at byte zero, `stride` bytes apart. The first CRC
/// initializes the accumulator directly, including when `blocksize` is zero.
pub fn fold(bytes: &[u8], stride: usize, count: usize, blocksize: u32) -> Option<u32> {
    if required_len(stride, count)? > bytes.len() {
        return None;
    }
    // The validated slice bounds every CRC read.
    Some(unsafe { fold_raw(bytes.as_ptr(), stride, count, blocksize) })
}

// Multiply a uniform CRC length operator by a CRC in the reflected polynomial.
// Used for table squaring, length-bit products and ordered CRC application.
const fn apply_operator(operator: u32, mut value: u32) -> u32 {
    if operator == 0 {
        return 0;
    }
    let mut mask = 1u32 << 31;
    let mut product = 0;
    loop {
        if operator & mask != 0 {
            product ^= value;
            if operator & (mask - 1) == 0 {
                break;
            }
        }
        mask >>= 1;
        value = (value >> 1) ^ if value & 1 != 0 { 0xedb8_8320 } else { 0 };
    }
    product
}

// Reads exactly the four CRC bytes per entry, allowing unreadable MD5 gaps
// in a foreign allocation and avoiding native-u32 alignment assumptions.
unsafe fn fold_raw(bytes: *const u8, stride: usize, count: usize, blocksize: u32) -> u32 {
    // Generate the uniform length operator directly, avoiding multiplication
    // by the identity before applying it to actual packet CRCs.
    let operator = if count > 1 && blocksize != 0 {
        length_operator(blocksize)
    } else {
        0
    };
    let mut result = 0;
    for i in 0..count {
        let block = u32::from_le_bytes(bytes.add(i * stride).cast::<[u8; 4]>().read_unaligned());
        result = if i == 0 {
            block
        } else if blocksize == 0 {
            result
        } else {
            apply_operator(operator, result) ^ block
        };
    }
    result
}

/// Fold packet CRCs with no allocation or native-u32 alignment assumption.
/// Returns 1 on success, 0 for an invalid descriptor; errors leave `out` untouched.
///
/// # Safety
/// For nonzero `count`, `bytes` must name one allocation containing at least
/// `(count - 1) * stride + 4` bytes. `len` bounds that span; each four-byte
/// CRC must be readable and initialized. Gaps need not be readable.
/// `out` must be a writable, aligned u32 disjoint from the input. No input
/// bytes are read except the four-byte little-endian CRC at each stride.
#[no_mangle]
pub unsafe extern "C" fn nzbget_rs_parcrc_batch(
    bytes: *const u8,
    len: usize,
    stride: usize,
    count: usize,
    blocksize: u32,
    out: *mut u32,
) -> i32 {
    if out.is_null() || len > isize::MAX as usize {
        return 0;
    }
    let Some(required) = required_len(stride, count) else {
        return 0;
    };
    if required > len || (count != 0 && bytes.is_null()) {
        return 0;
    }
    let result = fold_raw(bytes, stride, count, blocksize);
    out.write(result);
    1
}

// Reflected powers x^(2^k), k=0..31, generated by repeated squaring from
// x^1 (bit 30). This is the polynomial/bit convention used by crc::combine;
// no packet layout or host byte order enters the table. The independent
// public combine implementation remains the length/CRC test oracle.
const LENGTH_POWERS: [u32; 32] = {
    let mut powers = [0; 32];
    powers[0] = 1 << 30;
    let mut k = 1;
    while k < powers.len() {
        powers[k] = apply_operator(powers[k - 1], powers[k - 1]);
        k += 1;
    }
    powers
};

fn length_operator(length: u32) -> u32 {
    if length == 0 {
        return 1 << 31;
    }
    // Bytes correspond to eight bits. The &31 wrap exactly matches the
    // existing combine primitive, including the high three u32 length bits.
    let first = length.trailing_zeros() as usize;
    let mut operator = LENGTH_POWERS[(first + 3) & 31];
    let mut remaining = length & (length - 1);
    while remaining != 0 {
        let bit = remaining.trailing_zeros() as usize;
        operator = apply_operator(LENGTH_POWERS[(bit + 3) & 31], operator);
        remaining &= remaining - 1;
    }
    operator
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn operator_matches_independent_combine_at_length_bit_boundaries() {
        let mut lengths = vec![0, 1, u32::MAX, 512, 716800];
        for bit in 0..32 {
            let power = 1u32 << bit;
            lengths.extend([power - 1, power, power.saturating_add(1)]);
        }
        let mut state = 0x7061_7263u32;
        for _ in 0..10_000 {
            state ^= state << 13;
            state ^= state >> 17;
            state ^= state << 5;
            lengths.push(state);
        }
        for length in lengths {
            let operator = length_operator(length);
            assert_eq!(
                operator,
                crc::combine(1 << 31, 0, length),
                "length {length}"
            );
            for value in [0, 1, 0x8000_0000, 0x1234_5678, u32::MAX] {
                assert_eq!(
                    apply_operator(operator, value),
                    crc::combine(value, 0, length),
                    "length {length}, value {value:#x}"
                );
            }
        }
    }
}
