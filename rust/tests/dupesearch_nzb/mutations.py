#!/usr/bin/env python3
"""Prove the independent C++ differential rejects four behavioral mutations."""
import pathlib,subprocess,tempfile
root=pathlib.Path(__file__).resolve().parents[3];work=root/'rust/tests/dupesearch_nzb/artifacts'
source=(root/'rust/src/dupesearch_nzb.rs').read_text()
mutations={
 'part_count':('pos < end - 1', 'pos <= end - 1'),
 'par_case':('*table.add(usize::from(a)) == i32::from(b)', 'i32::from(a) == i32::from(b)'),
 'yenc_whitespace':("b' ' | b'\\t' | b'\\r' | b'\\n' | 0x0b | 0x0c", "b' ' | b'\\t' | b'\\r' | b'\\n'"),
 'trim_whitespace':("let trim = |b| matches!(b, b' ' | b'\\t' | b'\\r' | b'\\n');", "let trim = |b| matches!(b, b' ' | b'\\t' | b'\\r' | b'\\n' | 0x0b | 0x0c);"),
}
lock=pathlib.Path(tempfile.gettempdir())/'nzbget-rust-benchmark.lock'
for name,(old,new) in mutations.items():
 assert source.count(old)==1,(name,source.count(old))
 path=work/(name+'.rs');path.write_text(source.replace(old,new))
 lib=work/(name+'.a')
 subprocess.run(['flock','-s',str(lock),str(pathlib.Path.home()/'.cargo/bin/rustc'),'--edition','2021','--crate-type','staticlib','--crate-name',name,'-O','-A','warnings','-C','panic=abort',str(path),'-o',str(lib)],check=True,cwd=root)
 # Reuse the real C++ caller object generated by run.py, changing only its linked Rust implementation.
 exe=work/(name+'-caller')
 subprocess.run(['flock','-s',str(lock),'g++',str(work/'caller.o'),str(lib),'-lxml2','-lssl','-lcrypto','-ldl','-lpthread','-lm','-o',str(exe)],check=True)
 result=subprocess.run([str(exe)],capture_output=True,text=True)
 assert result.returncode==1 and 'differs' in result.stderr,(name,result.returncode,result.stderr)
 print(name+': KILLED ('+result.stderr.strip()+')')
